import assert from 'node:assert/strict';
import { FloorGrid, castRay } from '../src/client/raycast-world.js';
import { ARENA_X, ARENA_Y, TILE_PX } from '../src/shared/tactics.js';
const grid = new FloorGrid([{ col: -3, row: -2, cols: 8, rows: 6 }]);
const x = ARENA_X + TILE_PX, y = ARENA_Y + TILE_PX;
assert.equal(castRay(grid, x, y, 1, 0).distance, 4 * TILE_PX);
assert.equal(castRay(grid, x, y, -1, 0).distance, 4 * TILE_PX);
assert.equal(castRay(grid, x, y, 0, 1).distance, 3 * TILE_PX);
assert.equal(castRay(grid, x, y, 0, -1).distance, 3 * TILE_PX);
assert.equal(castRay(grid, x, y, 1, .4).distance, 4 * TILE_PX, 'Unnormalized rays retain perpendicular depth');
const gate = { x: x + 20, y, min: y - 10, max: y + 10, vertical: true, material: 1 };
assert.equal(castRay(grid, x, y, 1, 0, [gate]).distance, 20);
assert.equal(castRay(grid, x, y, 1, 0, [gate]).material, 1);
assert.equal(castRay(grid, x, y + 20, 1, 0, [gate]).material, 0, 'No phantom wall outside the gate span');
assert.equal(castRay(grid, x, y, 1, 0, [], 7).distance, 7, 'Camera distance cap');
const joined = new FloorGrid([{ col: 0, row: 0, cols: 5, rows: 5 }, { col: 5, row: 2, cols: 8, rows: 1 }, { col: 13, row: 0, cols: 5, rows: 5 }]);
assert.equal(castRay(joined, ARENA_X + TILE_PX * 2.5, ARENA_Y + TILE_PX * 2.5, 1, 0).distance, TILE_PX * 15.5, 'Corridor seams remain open');
assert.equal(castRay(joined, ARENA_X + TILE_PX * 2.5, ARENA_Y + TILE_PX * 1.5, 1, 0).distance, TILE_PX * 2.5, 'Room wall blocks beside corridor');
console.log('PASS: DDA depths, negative cells, corridor seams, gates, and camera distance.');
import { playerBiteFrame, selectAttackReticle } from '../src/client/attack-presentation.js';
