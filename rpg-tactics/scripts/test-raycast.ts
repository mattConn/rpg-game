import { RaycastRenderer } from '../src/client/raycast-renderer.js';
// Exercise camera input independently of canvas/asset construction.
const camera = Object.create(RaycastRenderer.prototype) as RaycastRenderer;
camera.resetView();
const defaultYaw = camera.yaw;
camera.look(0, .5);
assert.equal(camera.yaw, defaultYaw, 'Vertical drag only changes elevation');
assert(Reflect.get(camera, 'cameraAngle') < Math.PI / 6, 'Camera can go shallower than 30 degrees');
camera.look(0, -2);
assert.equal(Reflect.get(camera, 'cameraAngle'), Math.PI * 30 / 180, 'Camera cannot go steeper than 30 degrees');
camera.look(2, 0);
assert(Math.abs(camera.yaw - defaultYaw) > Math.PI * 2, 'Horizontal orbit remains unrestricted');
camera.zoom(120);
camera.resetView();
assert.equal(camera.yaw, defaultYaw, 'Reset restores the diagonal overhead view');
assert.equal(Reflect.get(camera, 'cameraAngle'), Math.PI * 30 / 180, 'Reset restores 30 degrees');
assert.equal(Reflect.get(camera, 'cameraDistance'), 600, 'Reset restores ARPG framing');
console.log('PASS: adjustable camera angle, horizontal orbit, and overhead reset.');

import { bloodHits } from '../src/client/blood-effects.js';
const beforeHit = { player: { x: 0, y: 0 }, stats: { health: 100 }, corpses: [],
  enemies: [{ id: 'hound', kind: 'hellhound', x: 50, y: 0, health: 20 }] } as unknown as TacticsSnapshot;
const afterHit = structuredClone(beforeHit);
afterHit.stats.health = 90;
afterHit.enemies[0]!.health = 10;
assert.equal(bloodHits(beforeHit, afterHit).length, 2, 'Simultaneous incoming and outgoing damage both splatter');
assert.equal(bloodHits(afterHit, afterHit).length, 0, 'Repeated snapshots do not replay blood');
const lethalHit = structuredClone(afterHit);
lethalHit.enemies = [];
lethalHit.corpses = [{ ...afterHit.enemies[0]! }];
assert.equal(bloodHits(afterHit, lethalHit).length, 1, 'Lethal removal still spatters');
lethalHit.corpses = [];
assert.equal(bloodHits(afterHit, lethalHit).length, 0, 'Removal without a corpse is not a hit');
const healed = structuredClone(beforeHit);
healed.stats.health = 110;
assert.equal(bloodHits(beforeHit, healed).length, 0, 'Healing does not splatter');
console.log('PASS: damage blood, lethal hits, repeated snapshots, removals, and healing.');

import { FloorStats } from '../src/client/floor-stats.js';
let savedStats = '';
const statsStorage = { getItem: () => savedStats || null, setItem: (_key: string, value: string) => { savedStats = value; } };
const ledger = new FloorStats(statsStorage);
const floorSnap = { floorRunId: 'run-1', killCount: 2, enemies: [{}], tombstones: [{ x: 1, y: 2, gameElapsedMs: 50 }] } as unknown as TacticsSnapshot;
assert.equal(ledger.update('1', 1, floorSnap).deaths, 1);
assert.equal(ledger.update('1', 1, floorSnap).deaths, 1, 'Repeated snapshots do not add deaths');
floorSnap.killCount = 0; floorSnap.enemies = [{}, {}, {}] as TacticsSnapshot['enemies'];
assert.equal(ledger.update('1', 1, floorSnap).enemiesKilled, 0, 'Reset replaces prior attempt kills');
assert.equal(ledger.floors.get('1')!.totalEnemies, 3, 'Floor enemy total stays balanced after reset');
floorSnap.floorRunId = 'run-2';
ledger.update('2', 2, floorSnap);
assert.equal(ledger.totalDeaths, 2, 'Total deaths sums floors');
const restored = new FloorStats(statsStorage);
assert.equal(restored.totalDeaths, 2, 'Floor records survive reload');
assert.equal(restored.csv(), 'seed,deaths,enemies killed/total\r\n1,1,0/3\r\n2,1,0/3\r\n');
console.log('PASS: floor stats, resets, death deduplication, persistence, CSV, and enemy totals.');

