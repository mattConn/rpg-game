// Generate texture variants without changing originals, UVs, alpha, or model geometry.
import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
import sharp from 'sharp';

const app = fileURLToPath(new URL('../', import.meta.url));
const sources = [
  [join(app, '../public/models'), '/shared-models'],
  [join(app, '../public/textures'), '/shared-textures'],
  [join(app, 'public/textures'), '/textures'],
];
const manifest = {};
const totals = { low: { original: 0, generated: 0 }, med: { original: 0, generated: 0 } };
async function* files(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) yield* files(path);
    else yield path;
  }
}
async function resize(data, cap) {
  const meta = await sharp(data).metadata();
  const output = await sharp(data).resize({ width: cap, height: cap, fit: 'inside', withoutEnlargement: true }).toBuffer();
  const resized = await sharp(output).metadata();
  assert(resized.width <= cap && resized.height <= cap);
  assert.equal(resized.hasAlpha, meta.hasAlpha);
  return { data: output, original: meta.width * meta.height, generated: resized.width * resized.height };
}
function packGlb(doc, binary) {
  const json = Buffer.from(JSON.stringify(doc));
  const paddedJson = Buffer.alloc(Math.ceil(json.length / 4) * 4, 0x20); json.copy(paddedJson);
  const paddedBin = Buffer.alloc(Math.ceil(binary.length / 4) * 4); binary.copy(paddedBin);
  const header = Buffer.alloc(20);
  header.writeUInt32LE(0x46546c67, 0); header.writeUInt32LE(2, 4);
  header.writeUInt32LE(28 + paddedJson.length + paddedBin.length, 8);
  header.writeUInt32LE(paddedJson.length, 12); header.writeUInt32LE(0x4e4f534a, 16);
  const binHeader = Buffer.alloc(8);
  binHeader.writeUInt32LE(paddedBin.length, 0); binHeader.writeUInt32LE(0x004e4942, 4);
  return Buffer.concat([header, paddedJson, binHeader, paddedBin]);
}
for (const [dir, prefix] of sources) for await (const path of files(dir)) {
  if (!/\.(png|jpe?g|glb)$/i.test(path)) continue;
  const original = await readFile(path);
  const isGlb = path.endsWith('.glb');
  let source, binary;
  if (isGlb) {
    const length = original.readUInt32LE(12);
    source = JSON.parse(original.subarray(20, 20 + length));
    if (!source.images?.length) continue;
    assert(source.buffers.length === 1 && !source.buffers[0].uri);
    binary = original.subarray(28 + length);
  }
  const url = `${prefix}/${relative(dir, path).replaceAll('\\', '/')}`;
  manifest[url] = {};
  for (const [quality, cap] of [['low', 256], ['med', 1024]]) {
    let output;
    if (isGlb) {
      const doc = structuredClone(source), chunks = [];
      const imageViews = new Set(doc.images.map(image => image.bufferView));
      assert(!imageViews.has(undefined), 'Expected embedded images');
      let offset = 0;
      for (let i = 0; i < doc.bufferViews.length; i++) {
        const view = doc.bufferViews[i];
        let data = binary.subarray(view.byteOffset || 0, (view.byteOffset || 0) + view.byteLength);
        if (imageViews.has(i)) {
          const result = await resize(data, cap); data = result.data;
          totals[quality].original += result.original; totals[quality].generated += result.generated;
        }
        view.byteOffset = offset; view.byteLength = data.length;
        const padded = Buffer.alloc(Math.ceil(data.length / 4) * 4); data.copy(padded);
        chunks.push(padded); offset += padded.length;
      }
      doc.buffers[0].byteLength = offset;
      // Geometry and animation accessors still address the same unchanged bytes.
      assert.deepEqual(doc.accessors, source.accessors);
      output = packGlb(doc, Buffer.concat(chunks));
    } else {
      const result = await resize(original, cap); output = result.data;
      totals[quality].original += result.original; totals[quality].generated += result.generated;
    }
    const target = `/graphics/${quality}${url}`;
    const destination = join(app, 'public', target);
    await mkdir(dirname(destination), { recursive: true });
    await writeFile(destination, output);
    manifest[url][quality] = target;
  }
}
await writeFile(join(app, 'src/client/texture-manifest.ts'),
  '// Generated by npm run build:textures. Only existing assets are redirected.\n' +
  'export const TEXTURE_VARIANTS: Record<string, { low: string; med: string }> = ' + JSON.stringify(manifest, null, 2) + ';\n');
console.log(`${Object.keys(manifest).length} texture/model sources generated for each preset.`);
for (const [quality, stats] of Object.entries(totals))
  console.log(`${quality}: ${(stats.original / 1e6).toFixed(1)}M -> ${(stats.generated / 1e6).toFixed(1)}M texture pixels (${Math.round(100 * (1 - stats.generated / stats.original))}% less)`);
